export type DocStatus = 'ok' | 'new' | 'check';
export type Doc = {
  id: number; type: string; no: string; cp: string; date: string; sum: number; vat: number;
  st: DocStatus; src: string; conf: number; kind: string; lines: [string, string, number, string][];
  /** рік документа, якщо не поточний (дата зберігається як дд.мм) */
  y?: string;
  /** поля розпізнаних та імпортованих документів */
  acc?: string; edrpou?: string; checks?: { ok: boolean; t: string; info?: boolean; field?: 'cp' | 'no' | 'date' | 'sum' | 'acc'; addCompany?: string; dupOf?: number }[];
  /** контрагент так, як його прочитала модель (до підстановки з довідника) */
  cpRead?: string; note?: string;
  /** коментар до документа: рукописні приписки на полях (телефон, ім’я) або текст бухгалтера; на облік не впливає */
  comment?: string;
  /** номенклатура: найменування, кількість, одиниця, ціна, сума */
  items?: { name: string; qty: number | null; unit: string | null; price: number | null; amount: number | null; nom?: string }[];
  /** підстава грошового документа (договір, заявка, рахунок, накладна, період) і стаття руху коштів */
  refs?: { contract_no?: string | null; contract_date?: string | null; order_no?: string | null; invoice_no?: string | null; primary_no?: string | null; period?: string | null };
  cf?: string;
  /** коли вивантажено в BAS (ISO-дата); порожньо — ще не вивантажено */
  basAt?: string;
};
export type BankRow = { d: string; cp: string; p: string; s: number; dt: string; kt: string; st: DocStatus };
export type Question = { id: string; icon: string; title: string; meta: string[]; opts: [string, string][]; doc?: number };
export type ReportStatus = 'ready' | 'sent' | 'draft';
export type Report = { name: string; per: string; due: string; st: ReportStatus };
export type CloseStep = { t: string; s: string; done: boolean; key?: 'bank' | 'docs' | 'assets' };

