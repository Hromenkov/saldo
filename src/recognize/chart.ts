const num = (acc: string) => acc.trim().split(' ')[0];
const re = (p: string) => new RegExp(`^(${p})$`);

export type LineIssue = { line: number; t: string };

/** Перевірка проводок: кожен рахунок є в плані, кожна пара Дт/Кт допустима. */
export function checkLines(lines: [string, string, ...unknown[]][]): LineIssue[] {
  const out: LineIssue[] = [];
  lines.forEach(([dt, kt], i) => {
    const d = num(dt), k = num(kt);
    for (const a of [d, k]) if (!CHART[a]) out.push({ line: i, t: `Рахунку ${a} немає в плані рахунків` });
    if (CHART[d] && CHART[k] && !CORR.some(([pd, pk]) => re(pd).test(d) && re(pk).test(k))) out.push({ line: i, t: `Кореспонденція Дт ${d} Кт ${k} не передбачена шаблонами` });
  });
  return out;
}

/** Рахунок підходить до виду документа? */
export const fitsKind = (kind: string, acc: string) => !KIND_ACCOUNTS[kind] || KIND_ACCOUNTS[kind].includes(num(acc));
export const isCostAccount = (acc: string) => COST_ACCOUNTS.includes(num(acc));

/** Рахунок за призначенням платежу: спершу податки, і лише потім зарплата («ПДФО із зарплати» — це 6411). */
export function purposeAccount(purpose: string): string | undefined {
  return ['6411', '642', '651', '6412', '6413', '661'].find(k => TAX_PURPOSE[k].test(purpose));
}
